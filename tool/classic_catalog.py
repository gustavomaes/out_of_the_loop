#!/usr/bin/env python3
"""Validate Classic launch content and regenerate its offline Dart bundle/report."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'assets/content/classic_catalog.json'
BUNDLE = ROOT / 'lib/src/data/classic/classic_catalog.g.dart'
REPORT = ROOT / 'docs/classic/catalog-report.json'


def build():
    data = json.loads(SOURCE.read_text())
    assert data['schemaVersion'] == 1 and data['catalogVersion']
    categories = data['categories']
    assert len(categories) == 23
    assert sum(not c['premium'] for c in categories) == 3
    ids, keys, category_ids = set(), set(), set()
    rows = []
    for c in categories:
        assert c['id'] not in category_ids
        category_ids.add(c['id'])
        assert len(c['words']) >= 40, c['id']
        texts, local_ids, languages = set(), set(), {}
        for w in c['words']:
            assert w['id'] not in ids and w['id'].strip()
            ids.add(w['id'])
            local_ids.add(w['id'])
            assert 'questions' not in w and isinstance(w['commercialExample'], bool)
            assert 'en' in w['value']
            for lang, text in w['value'].items():
                assert lang in {'en', 'pt-BR', 'es', 'hi', 'ar'}
                assert text and text == text.strip()
                normalized = (lang, text.casefold())
                assert normalized not in texts, (c['id'], normalized)
                texts.add(normalized)
                languages[lang] = languages.get(lang, 0) + 1
                keys.add(f"{lang}/{c['id']}/{w['id']}")
        assert set(c['paywallExampleIds']) <= local_ids
        assert all(w['commercialExample'] == (w['id'] in c['paywallExampleIds'])
                   for w in c['words'])
        rows.append({'category': c['id'], 'premium': c['premium'],
                     'concepts': len(c['words']), 'localizedValues': languages,
                     'humanReview': 'pending',
                     'reviewTopics': ['ambiguity', 'age suitability', 'cultural familiarity',
                                      'translation quality', 'US audience testing']})
    # Keep the prototype's contextual paywall examples backed by real content.
    prototype = (ROOT / 'prototypes/oddly/subscription-catalog.js').read_text()
    examples = json.loads(re.search(r'const PREMIUM_EXAMPLES = (\[.*\]);', prototype).group(1))
    for category, _, _, values in examples:
        c = next(c for c in categories if c['id'] == category)
        actual = {w['value']['en'] for w in c['words'] if w['id'] in c['paywallExampleIds']}
        assert set(values) == actual, category
    for c in categories:
        if not c['premium']:
            assert all(set(w['value']) == {'en', 'pt-BR', 'es', 'hi', 'ar'} for w in c['words'])
    mapping = data['legacyWordIds']
    assert all(v in keys for v in mapping.values())
    # Every installed legacy concept/translation retains an explicit equivalent.
    for bank in ['seed_content', 'us_game_night']:
        for c in json.loads((ROOT / f'assets/content/{bank}.json').read_text())['categories']:
            for w in c['words']:
                for lang in w['value']:
                    key = f"{lang}:{c['id']}:{w['id']}"
                    assert key in mapping, key
                    dest = mapping[key].split('/')
                    target = next(x for x in categories if x['id'] == dest[1])
                    target_word = next(x for x in target['words'] if x['id'] == dest[2])
                    assert target_word['value'][lang] == w['value'][lang], key
    # Report cross-category reuse separately; translations never increase concepts.
    owners = {}
    for c in categories:
        for w in c['words']:
            owners.setdefault(w['value']['en'].casefold(), []).append(c['id'])
    free = {w['value']['en'].casefold() for c in categories if not c['premium'] for w in c['words']}
    premium = set(owners) - free
    assert len(free) == 120 and len(premium) == 800
    reused = {word: cats for word, cats in owners.items() if len(cats) > 1}
    encoded = json.dumps(data, ensure_ascii=False, separators=(',', ':'))
    bundle = "// Generated by tool/classic_catalog.py; edit the JSON source.\nconst classicCatalogJson = r'''" + encoded + "''';\n"
    report = json.dumps({'catalogVersion': data['catalogVersion'],
                         'freeConcepts': len(free), 'premiumExclusiveConcepts': len(premium),
                         'categoryEntries': sum(len(c['words']) for c in categories),
                         'legacyLocalizedReferences': len(mapping),
                         'distinctEnglishTexts': len(owners),
                         'crossCategoryReuse': reused,
                         'humanReview': 'pending', 'categories': rows},
                        ensure_ascii=False, indent=2) + '\n'
    return bundle, report


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    bundle, report = build()
    for path, expected in [(BUNDLE, bundle), (REPORT, report)]:
        if args.check:
            assert path.read_text() == expected, f'Stale generated file: {path}'
        else:
            path.write_text(expected)
    print('Classic classic-1: 120 free + 800 exclusive Premium texts (959 category entries); human review pending.')
